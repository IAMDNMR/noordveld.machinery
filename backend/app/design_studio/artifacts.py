def _ts_regex(pattern: str) -> str:
    return "/" + pattern.replace("/", "\\/") + "/"


def validation_source(definition: ApplicationDefinition) -> str:
    rules = {entity.id: entity_rules(entity) for entity in definition.business.entities}
    formats = (
        "{ "
        + ", ".join(
            f"{json.dumps(key)}: {_ts_regex(value)}" for key, value in sorted(FORMATS.items())
        )
        + " }"
    )
    patterns = (
        "{ "
        + ", ".join(
            f"{json.dumps(key)}: {_ts_regex(value)}" for key, value in sorted(PATTERNS.items())
        )
        + " }"
    )
    return _header(definition) + VALIDATION_SOURCE.replace("__FORMATS__", formats).replace(
        "__PATTERNS__", patterns
    ).replace("__RULES__", _dump(rules))


def validation_cases(definition: ApplicationDefinition) -> list[dict]:
    cases = []
    for entity in definition.business.entities:
        rules = entity_rules(entity)
        valid = sample_record(rules)

        def case(description: str, record: dict, mode: str = "create"):
            expected = [
                f"{error['field']}:{error['code']}"
                for error in validate_record(rules, record, mode)
            ]
            cases.append(
                {
                    "entity": entity.id,
                    "description": description,
                    "mode": mode,
                    "record": record,
                    "expected": expected,
                }
            )

        case("a complete valid record is accepted", valid)
        for rule in rules:
            if rule["system_managed"]:
                case(f"{rule['id']} cannot be submitted", {**valid, rule["id"]: "x"})
                continue
            without = {key: value for key, value in valid.items() if key != rule["id"]}
            if rule["required"]:
                case(f"{rule['id']} is required on create", without)
                case(f"{rule['id']} may be omitted on update", without, "update")
            if rule["enum"]:
                case(
                    f"{rule['id']} rejects a value outside the list",
                    {**valid, rule["id"]: "NOT_ALLOWED"},
                )
            if rule["minimum"] is not None:
                case(
                    f"{rule['id']} rejects a value below the minimum",
                    {**valid, rule["id"]: rule["minimum"] - 1},
                )
            if rule["maximum"] is not None:
                case(
                    f"{rule['id']} rejects a value above the maximum",
                    {**valid, rule["id"]: rule["maximum"] + 1},
                )
            if rule["format"]:
                case(f"{rule['id']} rejects a malformed value", {**valid, rule["id"]: "not valid"})
        case("an unknown field is rejected", {**valid, "unexpected_field": "x"})
    return cases


def tests_source(definition: ApplicationDefinition) -> str:
    return _header(definition) + TEST_SOURCE.replace(
        "__CASES__", _dump(validation_cases(definition))
    )


def json_schema(entity: BusinessEntity, definition: ApplicationDefinition) -> dict:
    properties = {}
    for attribute in entity.attributes:
        prop: dict = {
            "type": [JSON_TYPES[attribute.type], "null"]
            if attribute.allow_unknown
            else JSON_TYPES[attribute.type],
            "title": attribute.name,
            "x-value-source": attribute.value_source,
            "x-sensitivity": attribute.sensitivity,
        }
        if attribute.description:
            prop["description"] = attribute.description
        if attribute.system_managed or not attribute.writable:
            prop["readOnly"] = True
        fmt = JSON_FORMATS.get(attribute.format or attribute.type)
        if fmt:
            prop["format"] = fmt
        if (
            attribute.format
            and attribute.format in FORMATS
            and attribute.format not in JSON_FORMATS
        ):
            prop["pattern"] = FORMATS[attribute.format]
        if attribute.pattern:
            prop["pattern"] = PATTERNS[attribute.pattern]
        for key, value in (
            ("minimum", attribute.minimum),
            ("maximum", attribute.maximum),
            ("minLength", attribute.min_length),
            ("maxLength", attribute.max_length),
        ):
            if value is not None:
                prop[key] = value
        if attribute.enum:
            prop["enum"] = list(attribute.enum)
        if attribute.default is not None:
            prop["default"] = attribute.default
        if attribute.reference:
            prop["x-reference"] = attribute.reference.model_dump()
        properties[attribute.id] = prop
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"urn:noordveld-design:{definition.id}:{entity.id}",
        "title": entity.name,
        "type": "object",
        "additionalProperties": False,
        "properties": properties,
        "required": sorted(attribute.id for attribute in entity.attributes if attribute.required),
        "x-relationships": [relation.model_dump() for relation in entity.relationships],
        "x-source-system": entity.source_system,
    }


def openapi(definition: ApplicationDefinition, links: dict[str, list[dict]] | None = None) -> dict:
    """A contract for the operations the process implies. No server implementation is generated. `links` adds
    relationship link fields (references the entity declares no attribute for) to each input schema."""
    entities = {entity.id: entity for entity in definition.business.entities}
    names = type_names(definition.business.entities)
    schemas: dict = {
        "Error": {
            "type": "object",
            "required": ["code", "message"],
            "properties": {"code": {"type": "string"}, "message": {"type": "string"}},
        }
    }
    for entity in definition.business.entities:
        schemas[names[entity.id]] = {"$ref": f"../schemas/{entity.id}.schema.json"}
        writable = [a for a in entity.attributes if not a.system_managed and a.writable]
        entity_links = (links or {}).get(entity.id, [])
        schemas[f"{names[entity.id]}Input"] = {
            "type": "object",
            "additionalProperties": False,
            "required": sorted(
                [a.id for a in writable if a.required and not a.allow_unknown]
                + [link["field"] for link in entity_links if link["required"]]
            ),
            "properties": {
                **{
                    a.id: {"$ref": f"../schemas/{entity.id}.schema.json#/properties/{a.id}"}
                    for a in writable
                },
                **{
                    link["field"]: {
                        "type": "string",
                        "x-reference": link["target"],
                        "description": f"Reference to a {link['target']} record.",
                    }
                    for link in entity_links
                },
            },
        }
    errors = {
        "400": {
            "description": "Validation failed",
            "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Error"}}},
        },
        "401": {"description": "Not signed in"},
        "403": {"description": "The role lacks the required permission"},
        "409": {"description": "Conflict with the current state"},
    }
    paths: dict = {}
    for workflow, state in steps(definition):
        if not needs_screen(state) or state.kind == "end":
            continue
        common = {
            "tags": [workflow.name],
            "x-workflow": workflow.id,
            "x-step": state.id,
            "x-role": state.role_id,
            "x-required-permission": state.permission,
            "x-requirements": state.requirement_ids,
            "x-rules": state.rule_ids,
            "x-implementation": "not generated",
        }
        path: dict = {}
        if state.reads_entity_ids:
            path["get"] = {
                **common,
                "operationId": f"{state.id}_context",
                "summary": f"Data shown at: {state.label}",
                "responses": {
                    "200": {
                        "description": "Context for the step",
                        "content": {
                            "application/json": {
                                "schema": {
                                    "type": "object",
                                    "properties": {
                                        entity_id: {
                                            "$ref": f"#/components/schemas/{names[entity_id]}"
                                        }
                                        for entity_id in state.reads_entity_ids
                                    },
                                }
                            }
                        },
                    },
                    **{code: errors[code] for code in ("401", "403")},
                },
            }
        writable = [
            entity_id
            for entity_id in state.writes_entity_ids
            if any(not a.system_managed and a.writable for a in entities[entity_id].attributes)
        ]
        if writable or outgoing(workflow, state.id):
            body = {
                "type": "object",
                "properties": {
                    entity_id: {"$ref": f"#/components/schemas/{names[entity_id]}Input"}
                    for entity_id in writable
                },
            }
            path["post"] = {
                **common,
                "operationId": f"{state.id}_submit",
                "summary": f"Complete: {state.label}",
                "requestBody": {
                    "required": bool(writable),
                    "content": {"application/json": {"schema": body}},
                },
                "responses": {
                    "200": {"description": "Step completed; the response names the next step"},
                    **errors,
                },
            }
        if path:
            paths[f"/steps/{state.id}"] = path
    return {
        "openapi": "3.1.0",
        "info": {
            "title": f"{definition.metadata.name} (contract)",
            "version": f"revision-{definition.revision}",
            "description": "Contract only: derived from the approved process. No server implementation is generated.",
        },
        "paths": paths,
        "components": {"schemas": schemas},
    }


def permissions(definition: ApplicationDefinition) -> dict:
    business = definition.business
    step_rows = [
        {
            "workflow_id": workflow.id,
            "step_id": state.id,
            "role_id": state.role_id,
            "required_permission": state.permission,
            "writes": state.writes_entity_ids,
            "reads": state.reads_entity_ids,
        }
        for workflow, state in steps(definition)
        if state.kind not in ("start", "end")
    ]
    return {
        "roles": {
            role.id: {
                "name": role.name,
                "permissions": role.permissions,
                "approval_authority": role.approval_authority,
            }
            for role in business.roles
        },
        "steps": step_rows,
        "note": "Design-time permissions. The export does not enforce access; an implementation must check them on the server.",
    }


def decision_tables(definition: ApplicationDefinition) -> list[dict]:
    rules = {rule.id: rule for rule in definition.business.rules if rule.outcomes}
    tables = []
    for workflow, state in steps(definition):
        for output in state.outputs:
            if output not in rules:
                continue
            rows = [
                {
                    "outcome": outcome,
                    "next_steps": sorted(
                        edge.target
                        for edge in outgoing(workflow, state.id)
                        if edge.condition.field == output
                        and edge.condition.kind == "equals"
                        and str(edge.condition.value) == outcome
                    ),
                }
                for outcome in rules[output].outcomes
            ]
            tables.append(
                {
                    "workflow_id": workflow.id,
                    "step_id": state.id,
                    "rule_id": output,
                    "rule_status": rules[output].status,
                    "condition": rules[output].condition,
                    "rows": rows,
                }
            )
    return tables


def application_files(
    definition: ApplicationDefinition, links: dict[str, list[dict]] | None = None
) -> dict[str, bytes]:
    files = {
        "src/generated/models.ts": models_source(definition).encode("utf-8"),
        "src/generated/validation.ts": validation_source(definition).encode("utf-8"),
        "src/generated/validation.test.ts": tests_source(definition).encode("utf-8"),
        "api/openapi.json": _dump(openapi(definition, links)).encode("utf-8"),
        "design/permissions.json": _dump(permissions(definition)).encode("utf-8"),
        "design/decision-tables.json": _dump(
            {
                "tables": decision_tables(definition),
                "note": "Outcomes map to transitions; conditions are documentation only.",
            }
        ).encode("utf-8"),
    }
    for entity in definition.business.entities:
        files[f"schemas/{entity.id}.schema.json"] = _dump(json_schema(entity, definition)).encode(
            "utf-8"
        )
    return files


