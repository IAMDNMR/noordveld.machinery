def catalogue(paths: list[str]) -> dict:
    entries = []
    for path in sorted(paths):
        kind, note = next(
            (
                (kind, note)
                for prefix, kind, note in KINDS
                if path == prefix or (prefix.endswith("/") and path.startswith(prefix))
            ),
            ("manifest", "Generated file."),
        )
        if path.startswith("runtime/"):
            kind = (
                "configuration"
                if path.endswith(".json")
                else "documentation"
                if path.endswith(".md")
                else "executable"
            )
            note = "Runnable local application target. Server enforces sessions, record validation, references and process transitions; see runtime/README.md for limits."
        if "design/frontend.json" in paths and (path.startswith("src/") and path.endswith((".ts", ".tsx", ".css")) or path == "index.html"):
            kind = "executable"
            note = "Project-specific React source or trusted transport SDK. Saved source passed generation-time build checks; review application behavior before release."
        entries.append({"path": path, "kind": kind, "note": note, "generated": True})
    unsupported = (
        UNSUPPORTED
        if "runtime/server.py" not in paths
        else [
            {
                "artifact": "Production identity and deployment",
                "status": "unsupported",
                "reason": "Runtime is loopback-only with explicit synthetic demo identities.",
            },
            {
                "artifact": "External integrations and prose-only rules",
                "status": "unsupported",
                "reason": "No adapters or inferred policy. See runtime/schema.json for exact action blockers.",
            },
            {
                "artifact": "Automatic data migrations",
                "status": "unsupported",
                "reason": "A changed specification requires a fresh isolated database; existing data is never silently migrated.",
            },
        ]
    )
    return {
        "files": entries,
        "unsupported": unsupported,
        "validation": {
            "at_export": "The specification passed schema and reference validation; files are produced from that validated data.",
            "not_at_export": ["TypeScript compilation", "test execution", "build"],
            "how_to_verify": "See BUILD.md: npm run typecheck and npm test check the generated source.",
        },
    }


