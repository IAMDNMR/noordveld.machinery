"""Deterministic application artifacts from an approved specification.

Every generated source file is a fixed template plus JSON data serialized from the validated specification: no
specification text is spliced into code, nothing is executed here, and nothing reaches the network. Each artifact is
classified honestly in `design/artifacts.json`: executable source, contract, manifest, or documentation; what cannot be
generated reliably is listed as unsupported.
"""

